# RR Trading One - shared helpers for the infrastructure scripts (Windows PowerShell 5.1 compatible).

function Step([string]$m) { Write-Host ""; Write-Host "== $m" -ForegroundColor Cyan }
function Info([string]$m) { Write-Host "   $m" }
function Warn([string]$m) { Write-Host "   WARNING: $m" -ForegroundColor Yellow }

function Assert-Admin {
    $id = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
    if (-not $id.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { throw "Run this script as Administrator." }
}

function New-Secret([int]$bytes = 32) {
    $b = New-Object byte[] $bytes
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    return ([Convert]::ToBase64String($b)).TrimEnd("=").Replace("+", "-").Replace("/", "_")
}

function New-FernetKey {
    $b = New-Object byte[] 32
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    return ([Convert]::ToBase64String($b)).Replace("+", "-").Replace("/", "_")      # url-safe, padded (Fernet)
}

function Read-EnvFile([string]$path) {
    $h = @{}
    if (Test-Path $path) {
        foreach ($line in [IO.File]::ReadAllLines($path)) {
            if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)=(.*)$') { $h[$Matches[1]] = $Matches[2] }
        }
    }
    return $h
}

function Write-EnvFile([string]$path, $values) {
    $lines = @("# RR Trading One engine settings - generated by provision.ps1. Contains secrets: do not share.")
    foreach ($k in $values.Keys) { $lines += "$k=$($values[$k])" }
    $tmp = "$path.tmp"
    [IO.File]::WriteAllText($tmp, (($lines -join "`r`n") + "`r`n"), (New-Object Text.UTF8Encoding($false)))   # no BOM
    Move-Item -Force $tmp $path
}

function Invoke-Checked([string]$exe, [string[]]$arguments, [int[]]$AllowedExit = @(0)) {
    $old = $ErrorActionPreference; $ErrorActionPreference = "Continue"
    try { & $exe @arguments; $code = $LASTEXITCODE } finally { $ErrorActionPreference = $old }
    if ($AllowedExit -notcontains $code) { throw "$([IO.Path]::GetFileName($exe)) failed with exit code $code" }
}

function Invoke-Installer([string]$exe, [string[]]$arguments, [int[]]$AllowedExit = @(0)) {
    # GUI installers return immediately when called with '&'; wait for the process itself.
    $quoted = $arguments | ForEach-Object { if ($_ -match '\s' -and $_ -notmatch '^".*"$') { if ($_ -match '^([^=]+)=(.*)$') { "$($Matches[1])=`"$($Matches[2])`"" } else { "`"$_`"" } } else { $_ } }
    $p = Start-Process -FilePath $exe -ArgumentList ($quoted -join " ") -PassThru -WindowStyle Hidden
    $p.WaitForExit()
    if ($AllowedExit -notcontains $p.ExitCode) { throw "$([IO.Path]::GetFileName($exe)) failed with exit code $($p.ExitCode)" }
}

function Get-VerifiedComponent([string]$Name, $Spec, [string]$DownloadDir) {
    $file = Join-Path $DownloadDir ([IO.Path]::GetFileName(([Uri]$Spec.url).AbsolutePath))
    $pinned = ($Spec.PSObject.Properties.Name -contains "sha256") -and $Spec.sha256
    $signer = if ($Spec.PSObject.Properties.Name -contains "signer") { $Spec.signer } else { "" }
    if ((Test-Path $file) -and $pinned -and ((Get-FileHash $file -Algorithm SHA256).Hash -ieq $Spec.sha256)) {
        Info "$Name $($Spec.version): cached, SHA-256 verified"
        return $file
    }
    Info "$Name $($Spec.version): downloading $($Spec.url)"
    Invoke-WebRequest -Uri $Spec.url -OutFile "$file.part" -UseBasicParsing
    Move-Item -Force "$file.part" $file
    $hash = (Get-FileHash $file -Algorithm SHA256).Hash.ToLower()
    if ($pinned) {
        if ($hash -ne $Spec.sha256.ToLower()) { Remove-Item $file -Force; throw "$Name SHA-256 mismatch: expected $($Spec.sha256), got $hash" }
        Info "$Name SHA-256 verified"
    }
    if ($signer) {
        $sig = Get-AuthenticodeSignature $file
        if ($sig.Status -ne "Valid" -or $sig.SignerCertificate.Subject -notmatch [regex]::Escape($signer)) {
            Remove-Item $file -Force
            throw "$Name Authenticode signature is not valid for '$signer' ($($sig.Status))"
        }
        Info "$Name Authenticode signature valid ($signer)"
    }
    if (-not $pinned -and -not $signer) { Remove-Item $file -Force; throw "$Name has no pinned SHA-256 or signer in components.json; refusing an unverified download" }
    return $file
}

function Copy-Tree([string]$from, [string]$to, [string[]]$excludeDirs) {
    New-Item -ItemType Directory -Force -Path $to | Out-Null
    $args2 = @($from, $to, "/MIR", "/NFL", "/NDL", "/NJH", "/NJS", "/NP", "/R:2", "/W:2", "/XD") + $excludeDirs
    $old = $ErrorActionPreference; $ErrorActionPreference = "Continue"
    try { & robocopy.exe @args2 | Out-Null; $code = $LASTEXITCODE } finally { $ErrorActionPreference = $old }
    if ($code -ge 8) { throw "robocopy $from -> $to failed ($code)" }
}

function Protect-Folder([string]$path) {
    # inheritance off; only SYSTEM and Administrators
    Invoke-Checked "icacls.exe" @($path, "/inheritance:r", "/grant:r", "*S-1-5-18:(OI)(CI)F", "*S-1-5-32-544:(OI)(CI)F") | Out-Null
}

function Grant-Path([string]$path, [string]$who, [string]$perm) {
    Invoke-Checked "icacls.exe" @($path, "/grant", "${who}:$perm") | Out-Null
}

function Wait-Until([string]$what, [scriptblock]$cond, [int]$seconds) {
    $deadline = (Get-Date).AddSeconds($seconds)
    while ((Get-Date) -lt $deadline) {
        try { if (& $cond) { Info "$what - OK"; return } } catch { }
        Start-Sleep -Seconds 2
    }
    throw "Timed out waiting for: $what"
}

function Test-ApiHealth([int]$port) {
    try {
        $r = Invoke-WebRequest -Uri "http://127.0.0.1:$port/api/health" -UseBasicParsing -TimeoutSec 5
        return ($r.StatusCode -eq 200 -and $r.Content -match '"ok"')
    } catch { return $false }
}

function Stop-EngineServices([string[]]$names) {
    foreach ($n in $names) {
        $s = Get-Service $n -ErrorAction SilentlyContinue
        if ($s -and $s.Status -ne "Stopped") { Info "stopping $n"; Stop-Service $n -Force; $s.WaitForStatus("Stopped", [TimeSpan]::FromSeconds(60)) }
    }
}

function Set-ServiceAccount([string]$name, [string]$account) {
    if ($account -like "NT SERVICE\*") {
        # Virtual (per-service) accounts: WMI's Change() rejects them (code 22); sc.exe supports them, no password.
        Invoke-Checked "sc.exe" @("config", $name, "obj=", $account) | Out-Null
    } else {
        $svc = Get-CimInstance Win32_Service -Filter "Name='$name'"
        $r = Invoke-CimMethod -InputObject $svc -MethodName Change -Arguments @{ StartName = $account; StartPassword = "" }
        if ($r.ReturnValue -ne 0) { throw "Could not set $name to run as $account (code $($r.ReturnValue))" }
    }
    $now = (Get-CimInstance Win32_Service -Filter "Name='$name'").StartName
    if ($now -ne $account) { throw "$name runs as '$now', expected '$account'" }
}

function Invoke-Engine([string]$python, [string[]]$arguments, [string]$backend, [string]$envFile, [string]$pgBin) {
    # Run an engine CLI with the protected settings file; returns stdout lines.
    $saved = @{ RR_ENV_FILE = $env:RR_ENV_FILE; RR_PG_BIN = $env:RR_PG_BIN; PYTHONPATH = $env:PYTHONPATH }
    $env:RR_ENV_FILE = $envFile; $env:RR_PG_BIN = $pgBin; $env:PYTHONPATH = $backend
    Push-Location $backend
    $old = $ErrorActionPreference; $ErrorActionPreference = "Continue"
    try { $out = & $python @arguments; $code = $LASTEXITCODE }
    finally {
        $ErrorActionPreference = $old; Pop-Location
        foreach ($k in $saved.Keys) { Set-Item "Env:\$k" -Value $saved[$k] -ErrorAction SilentlyContinue; if (-not $saved[$k]) { Remove-Item "Env:\$k" -ErrorAction SilentlyContinue } }
    }
    if ($code -ne 0) { throw "engine command failed ($code): python $($arguments -join ' ')" }
    return $out
}

function Install-WinSWService {
    param([string]$WinSW, [string]$Dir, [string]$Id, [string]$Name, [string]$Executable, [string]$Arguments,
          [string]$WorkingDir, [string]$StartMode, [string]$Account, [string]$Logs, [string[]]$Depends = @(),
          [hashtable]$Environment = @{})
    $exe = Join-Path $Dir "$Id.exe"
    Copy-Item $WinSW $exe -Force
    $envXml = ($Environment.Keys | Sort-Object | ForEach-Object { "  <env name=`"$_`" value=`"$([Security.SecurityElement]::Escape($Environment[$_]))`"/>" }) -join "`r`n"
    $depXml = ($Depends | ForEach-Object { "  <depend>$_</depend>" }) -join "`r`n"
    $xml = @"
<service>
  <id>$Id</id>
  <name>$Name</name>
  <description>$Name (RR Trading One). Logs: $([Security.SecurityElement]::Escape($Logs))</description>
  <executable>$([Security.SecurityElement]::Escape($Executable))</executable>
  <arguments>$([Security.SecurityElement]::Escape($Arguments))</arguments>
  <workingdirectory>$([Security.SecurityElement]::Escape($WorkingDir))</workingdirectory>
$envXml
$depXml
  <startmode>$StartMode</startmode>
  <delayedAutoStart>$(if ($StartMode -eq 'Automatic') { 'true' } else { 'false' })</delayedAutoStart>
  <onfailure action="restart" delay="10 sec"/>
  <onfailure action="restart" delay="30 sec"/>
  <onfailure action="none"/>
  <resetfailure>1 hour</resetfailure>
  <stoptimeout>30 sec</stoptimeout>
  <logpath>$([Security.SecurityElement]::Escape($Logs))</logpath>
  <log mode="roll-by-size"><sizeThreshold>10240</sizeThreshold><keepFiles>8</keepFiles></log>
</service>
"@
    [IO.File]::WriteAllText((Join-Path $Dir "$Id.xml"), $xml, (New-Object Text.UTF8Encoding($false)))
    if (-not (Get-Service $Id -ErrorAction SilentlyContinue)) { Invoke-Checked $exe @("install") | Out-Null }
    Set-Service $Id -StartupType $StartMode
    Set-ServiceAccount $Id $Account
    Info "$Id installed ($StartMode, runs as $Account)"
}

function Install-EngineService {
    param([string]$WinSW, [string]$Dir, [string]$Id, [string]$Name, [string]$StartMode, [string]$Arguments,
          [string]$Python, [string]$Backend, [string]$EnvFile, [string]$Logs, [string]$PgBin, [string]$Cache)
    $tmp = Join-Path $Cache "tmp\$Id"
    New-Item -ItemType Directory -Force -Path $tmp | Out-Null
    Install-WinSWService -WinSW $WinSW -Dir $Dir -Id $Id -Name $Name -Executable $Python -Arguments $Arguments `
        -WorkingDir $Backend -StartMode $StartMode -Account "NT SERVICE\$Id" -Logs $Logs `
        -Depends @("RRTradingOne-PostgreSQL", "RRTradingOne-Redis") `
        -Environment @{ PYTHONPATH = $Backend; RR_ENV_FILE = $EnvFile; RR_PG_BIN = $PgBin; PYTHONUTF8 = "1"
                        PYTHONDONTWRITEBYTECODE = "1"; TEMP = $tmp; TMP = $tmp }
    Grant-Path $tmp "NT SERVICE\$Id" "(OI)(CI)M"
    Grant-Path (Split-Path -Parent $Backend) "NT SERVICE\$Id" "(OI)(CI)RX"
}
